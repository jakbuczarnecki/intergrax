def resolve_script(basename: str) -> Path:
    """Resolve a script basename to an absolute path under scripts/."""
    rel = SCRIPT_PATHS.get(basename)
    if rel is None:
        msg = f"unknown CI script basename: {basename}"
        raise KeyError(msg)
    return SCRIPTS_ROOT / rel
