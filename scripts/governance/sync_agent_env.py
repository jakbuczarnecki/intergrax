def load_agents() -> dict[str, str]:
    """Canonical Claude Code agents (``agent-env/agents/igx-*.md``) as adapter text."""
    out: dict[str, str] = {}
    for path in sorted(_AGENTS.glob(f"{AGENT_PREFIX}*.md")):
        meta = _frontmatter(path)
        if meta.get("name") != path.stem:
            raise ValueError(f"{_rel(path)}: frontmatter name must equal file name {path.stem!r}")
        text = _read(path)
        end = _FRONTMATTER.match(text).end()  # type: ignore[union-attr]
        marker = f"<!-- {GENERATED} from agent-env/agents/{path.name} - do not edit. -->\n"
        out[path.stem] = text[:end] + marker + text[end:]
    return out


_WRITE_TOOLS = {"Edit", "Write", "Bash", "NotebookEdit"}


def _cursor_agent(path: Path) -> str:
    """Cursor subagent adapter: documented keys only; readonly is derived from the Claude tool list."""
    meta = _frontmatter(path)
    tools = {part.strip() for part in str(meta.get("tools", "")).split(",") if part.strip()}
    text = _read(path)
    body = text[_FRONTMATTER.match(text).end() :]  # type: ignore[union-attr]
    # Cursor uses Composer reviewers; the canonical Claude-only model routing must
    # not leak into the Cursor adapter. Keep the Claude source unmodified.
    if path.stem == "igx-reviewer":
        claude_instruction = (
            "- The orchestrator runs this agent on `opus` for classes M2S, M3 and EC, and on `sonnet` otherwise."
        )
        if body.count(claude_instruction) != 1:
            raise ValueError("igx-reviewer Claude routing instruction changed: update Cursor adapter")
        body = body.replace(
            claude_instruction,
            "- In Cursor this reviewer uses `composer-2.5` for every review class; "
            "formal independent IIAC certification remains a separate session.",
        )
    return (
        "---\n"
        f"name: {path.stem}\n"
        f"description: {_yaml_scalar(str(meta.get('description', '')))}\n"
        "model: composer-2.5\n"
        f"readonly: {'false' if tools & _WRITE_TOOLS else 'true'}\n"
        "---\n"
        f"<!-- {GENERATED} from agent-env/agents/{path.name} - do not edit. -->\n" + body
    )


def _claude_md_block(rules: dict[str, dict[str, str]]) -> str:
    always = [rid for rid, meta in rules.items() if meta["loading"] == "always"]
    on_demand = [rid for rid, meta in rules.items() if meta["loading"] in ("explicit", "auto")]
    lines = [
        f"{BLOCK_BEGIN} (scripts/governance/sync_agent_env.py) - do not edit; edit agent-env/rules/ and re-run -->"
    ]
    lines += [f"@agent-env/rules/{rid}.md" for rid in always]
    listed = ", ".join(f"`/{rid}`" for rid in on_demand)
    lines += [f"On-demand rules (skills, canonical text in `agent-env/rules/`): {listed}", BLOCK_END]
    return "\n".join(lines)


def _exemptions() -> set[str]:
    if not _EXEMPTIONS.is_file():
        return set()
    doc = yaml.safe_load(_read(_EXEMPTIONS)) or {}
    return {str(item) for item in doc.get("skill_body_lines", [])}


def size_problems() -> list[str]:
    """Size gates: L0 bytes, CLAUDE.md / AGENTS.md lines, description length, skill body length."""
    out: list[str] = []
    claude_text, agents_text = _read(_CLAUDE_MD), _read(_REPO / "AGENTS.md")
    always = [_RULES / f"{rid}.md" for rid, meta in load_rules().items() if meta["loading"] == "always"]
    l0 = sum(len(t.encode("utf-8")) for t in (claude_text, agents_text)) + sum(p.stat().st_size for p in always)
    if l0 > L0_MAX_BYTES:
        out.append(f"L0 (CLAUDE.md + AGENTS.md + always-on rules) is {l0} bytes, max {L0_MAX_BYTES}")
    for name, text, limit in (
        ("CLAUDE.md", claude_text, CLAUDE_MD_MAX_LINES),
        ("AGENTS.md", agents_text, AGENTS_MD_MAX_LINES),
    ):
        if len(text.splitlines()) > limit:
            out.append(f"{name}: {len(text.splitlines())} lines, max {limit}")
    for rid, meta in load_rules().items():
        if len(meta["description"]) > DESCRIPTION_MAX_CHARS:
            out.append(f"rule {rid}: description over {DESCRIPTION_MAX_CHARS} chars")
    exempt = _exemptions()
    for path in sorted(_SKILLS.glob("*/SKILL.md")):
        sid, text = path.parent.name, _read(path)
        if len(str(_frontmatter(path).get("description", ""))) > DESCRIPTION_MAX_CHARS:
            out.append(f"skill {sid}: description over {DESCRIPTION_MAX_CHARS} chars")
        body = _FRONTMATTER.sub("", text, count=1)
        if len(body.splitlines()) > SKILL_BODY_MAX_LINES and sid not in exempt:
            out.append(f"skill {sid}: body over {SKILL_BODY_MAX_LINES} lines (list it in size_exemptions.yaml)")
    for path in sorted(_AGENTS.glob(f"{AGENT_PREFIX}*.md")):
        body = _FRONTMATTER.sub("", _read(path), count=1)
        if len(body.strip().splitlines()) > AGENT_BODY_MAX_LINES:
            out.append(f"agent {path.stem}: body over {AGENT_BODY_MAX_LINES} lines")
    return out


def expected_files() -> dict[Path, str]:
    rules = load_rules(include_retired=True)
    skills = load_skills()
    out: dict[Path, str] = {}
    for rid, meta in rules.items():
        if meta["loading"] != "retired":  # tombstones add a listed rule description for nothing
            out[_CURSOR / "rules" / f"{rid}.mdc"] = _cursor_rule(rid, meta)
        if meta["loading"] not in ("always", "cursor-always", "retired"):
            out[_CLAUDE / "skills" / rid / "SKILL.md"] = _skill_adapter(
                rid,
                meta["description"],
                canonical=f"agent-env/rules/{rid}.md",
                kind="rule",
                explicit_only=meta["loading"] == "explicit",
            )
    for sid, meta in skills.items():
        canonical = f"agent-env/skills/{sid}/SKILL.md"
        for tool_dir in (_CURSOR, _CLAUDE):
            if tool_dir == _CURSOR and sid == "igx-run-plan":
                out[tool_dir / "skills" / sid / "SKILL.md"] = _cursor_native_plan_alias()
                continue
            if tool_dir == _CURSOR and sid == "igx-autonomy":
                out[tool_dir / "skills" / sid / "SKILL.md"] = _cursor_autonomy_stub()
                continue
            adapter = _skill_adapter(
                sid,
                str(meta["description"]),
                canonical=canonical,
                kind="skill",
                explicit_only=bool(meta["explicit_only"]),
            )
            note = _CURSOR_DIRECT_SKILL_NOTES.get(sid) if tool_dir == _CURSOR else None
            out[tool_dir / "skills" / sid / "SKILL.md"] = adapter + (f"\n{note}\n" if note else "")
    for aid, text in load_agents().items():
        out[_CLAUDE / "agents" / f"{aid}.md"] = text
    for path in sorted(_AGENTS.glob(f"{AGENT_PREFIX}*.md")):
        out[_CURSOR / "agents" / path.name] = _cursor_agent(path)
    out.update(_codex_files(rules, skills))
    return out


def _codex_files(rules: dict[str, dict[str, str]], skills: dict[str, dict[str, object]]) -> dict[Path, str]:
    """Codex-only projections; never change another harness's adapters or authority."""
    marker = f"<!-- {GENERATED} - do not edit. -->\n"
    guidance = marker + _read(_REPO / "AGENTS.md").rstrip() + "\n\n"
    for rid, meta in rules.items():
        if meta["loading"] == "always":
            guidance += _always_extract(rid) + "\n\n"
    guidance += _read(_CODEX / "AGENTS.md")
    out = {_REPO / "AGENTS.override.md": guidance}
    workflows = {
        sid: (str(meta["description"]), f"agent-env/skills/{sid}/SKILL.md", bool(meta["explicit_only"]))
        for sid, meta in skills.items()
    }
    workflows.update(
        {
            rid: (meta["description"], f"agent-env/rules/{rid}.md", meta["loading"] == "explicit")
            for rid, meta in rules.items()
            if meta["loading"] in ("explicit", "auto")
        }
    )
    for sid, (description, canonical, explicit) in workflows.items():
        folder = _CODEX / "plugin" / "skills" / f"codex-{sid}"
        body = (
            f"---\nname: codex-{sid}\ndescription: {_yaml_scalar(description)}\n---\n"
            + marker
            + "Apply the Codex vocabulary and lifecycle mapping in `.codex/AGENTS.md`.\n"
            + f"Read and follow the canonical workflow: `{canonical}` (Git worktree root).\n"
        )
        if explicit:
            body += "Operator invocation only; do not activate implicitly.\n"
        if sid == "igx-run-plan":
            body += (
                "In Codex, use `$intergrax-codex:codex-igx-run-plan <plan.md>`; `UserPromptSubmit` binds the plan "
                "to this session. `stop` clears it; `status` reports it. Follow the shared "
                "execution/decision rules, replacing Claude/Cursor start/stop commands and "
                "Stop-hook state with `.codex/hooks/igx_codex_guard.py`. Never call the shared "
                "`scripts/hooks/igx_stop_guard.py` from Codex.\n"
            )
        out[folder / "SKILL.md"] = body
