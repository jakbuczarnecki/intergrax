def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _frontmatter(path: Path) -> dict[str, object]:
    match = _FRONTMATTER.match(_read(path))
    if not match:
        raise ValueError(f"{path.relative_to(_REPO).as_posix()}: missing YAML frontmatter")
    meta = yaml.safe_load(match.group(1))
    if not isinstance(meta, dict):
        raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter must be a mapping")
    return meta


def _yaml_scalar(value: str) -> str:
    """Plain scalar when it round-trips through YAML, otherwise a quoted one."""
    try:
        if yaml.safe_load(f"k: {value}") == {"k": value}:
            return value
    except yaml.YAMLError:
        pass
    return json.dumps(value, ensure_ascii=False)


def load_rules(*, include_retired: bool = False) -> dict[str, dict[str, str]]:
    rules: dict[str, dict[str, str]] = {}
    for path in sorted(_RULES.glob("*.md")):
        meta = _frontmatter(path)
        description = str(meta.get("description", "")).strip()
        loading = str(meta.get("loading", "")).strip()
        if not description:
            raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter needs 'description'")
        if loading not in LOADING_MODES:
            raise ValueError(
                f"{path.relative_to(_REPO).as_posix()}: 'loading' must be one of {LOADING_MODES}, got {loading!r}"
            )
        if loading == "retired" and not include_retired:  # tombstone: no import, no skill adapter
            continue
        rules[path.stem] = {"description": description, "loading": loading}
    return rules


def load_skills() -> dict[str, dict[str, object]]:
    skills: dict[str, dict[str, object]] = {}
    for path in sorted(_SKILLS.glob("*/SKILL.md")):
        meta = _frontmatter(path)
        skill_id = path.parent.name
        description = str(meta.get("description", "")).strip()
        if meta.get("name") != skill_id:
            raise ValueError(f"{_rel(path)}: frontmatter name must equal directory {skill_id!r}")
        if not description:
            raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter needs 'description'")
        skills[skill_id] = {
            "description": description,
            "explicit_only": meta.get("disable-model-invocation") is True,
        }
    return skills


def _always_extract(rule_id: str) -> str:
    """Normative text of an always-on rule: its ``igx:active`` blocks, or the whole short body."""
    body = _FRONTMATTER.sub("", _read(_RULES / f"{rule_id}.md"), count=1).strip("\n")
    blocks = [match.group(1).strip("\n") for match in _ACTIVE_BLOCK.finditer(body)]
    if blocks:
        return "\n\n".join(blocks)
    if len(body.splitlines()) <= ALWAYS_INLINE_MAX_LINES:
        return body
    raise ValueError(
        f"agent-env/rules/{rule_id}.md: always-on rule body is over {ALWAYS_INLINE_MAX_LINES} lines "
        f"and has no {ACTIVE_START} ... {ACTIVE_END} block"
    )


