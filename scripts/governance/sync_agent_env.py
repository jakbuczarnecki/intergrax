def _cursor_rule(rule_id: str, meta: dict[str, str]) -> str:
    head = (
        "---\n"
        f"description: {_yaml_scalar(meta['description'])}\n"
        f"alwaysApply: {'true' if meta['loading'] in ('always', 'cursor-always') else 'false'}\n"
        "---\n"
        f"<!-- {GENERATED} from agent-env/rules/{rule_id}.md - do not edit. -->\n"
    )
    if meta["loading"] not in ("always", "cursor-always"):
        pointer = head + f"Canonical rule (SSOT): @agent-env/rules/{rule_id}.md\n"
        note = _CURSOR_DIRECT_RULE_NOTES.get(rule_id)
        return pointer + (f"\n{note}\n" if note else "")
    # Cursor does not expand "@" inside a rule body: the normative text must be inlined here.
    return (
        head
        + _cursor_core_text(rule_id, _always_extract(rule_id))
        + "\n\n"
        + f"Canonical rule (SSOT): `agent-env/rules/{rule_id}.md`. Read it only when editing rules "
        + "or when a section outside this extract is needed.\n"
    )


def _skill_adapter(skill_id: str, description: str, *, canonical: str, kind: str, explicit_only: bool) -> str:
    lines = ["---", f"name: {skill_id}", f"description: {_yaml_scalar(description)}"]
    if explicit_only:
        lines.append("disable-model-invocation: true")
    lines += [
        "---",
        f"<!-- {GENERATED} from {canonical} - do not edit. -->",
        f"Read and follow the canonical {kind} (SSOT): `{canonical}`",
        "",
    ]
    return "\n".join(lines)


