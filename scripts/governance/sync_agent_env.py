"""Generate thin Cursor / Claude Code adapters from the shared ``agent-env/`` SSOT.

Canonical content (rules, skills) lives only in ``agent-env/``. The tool folders hold
pointers that reference it:

* ``.cursor/rules/<id>.mdc``         one per rule (Cursor frontmatter + pointer)
* ``.cursor/skills/<id>/SKILL.md``   one per skill (pointer)
* ``.claude/skills/<id>/SKILL.md``   one per skill, plus one per non-always-on rule (pointer)
* ``CLAUDE.md``                      block between the ``agent-env:generated`` markers (always-on imports)

Usage::

    uv run python scripts/governance/sync_agent_env.py           # write adapters
    uv run python scripts/governance/sync_agent_env.py --check   # exit 1 on drift (CI / doctor)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

_REPO = Path(__file__).resolve().parents[2]
_ENV = _REPO / "agent-env"
_RULES = _ENV / "rules"
_SKILLS = _ENV / "skills"
_CURSOR = _REPO / ".cursor"
_CLAUDE = _REPO / ".claude"
_CLAUDE_MD = _REPO / "CLAUDE.md"

GENERATED = "GENERATED by scripts/governance/sync_agent_env.py"
BLOCK_BEGIN = "<!-- BEGIN agent-env:generated"
BLOCK_END = "<!-- END agent-env:generated -->"
LOADING_MODES = ("always", "explicit", "auto")

_FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _frontmatter(path: Path) -> dict[str, object]:
    match = _FRONTMATTER.match(_read(path))
    if not match:
        raise ValueError(f"{path.relative_to(_REPO).as_posix()}: missing YAML frontmatter")
    meta = yaml.safe_load(match.group(1))
    if not isinstance(meta, dict):
        raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter must be a mapping")
    return meta


def _yaml_scalar(value: str) -> str:
    """Plain scalar when it round-trips through YAML, otherwise a quoted one."""
    try:
        if yaml.safe_load(f"k: {value}") == {"k": value}:
            return value
    except yaml.YAMLError:
        pass
    return json.dumps(value, ensure_ascii=False)


def load_rules() -> dict[str, dict[str, str]]:
    rules: dict[str, dict[str, str]] = {}
    for path in sorted(_RULES.glob("*.md")):
        meta = _frontmatter(path)
        description = str(meta.get("description", "")).strip()
        loading = str(meta.get("loading", "")).strip()
        if not description:
            raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter needs 'description'")
        if loading not in LOADING_MODES:
            raise ValueError(
                f"{path.relative_to(_REPO).as_posix()}: 'loading' must be one of {LOADING_MODES}, got {loading!r}"
            )
        rules[path.stem] = {"description": description, "loading": loading}
    return rules


def load_skills() -> dict[str, dict[str, str]]:
    skills: dict[str, dict[str, str]] = {}
    for path in sorted(_SKILLS.glob("*/SKILL.md")):
        meta = _frontmatter(path)
        skill_id = path.parent.name
        description = str(meta.get("description", "")).strip()
        if meta.get("name") != skill_id:
            raise ValueError(f"{_rel(path)}: frontmatter name must equal directory {skill_id!r}")
        if not description:
            raise ValueError(f"{path.relative_to(_REPO).as_posix()}: frontmatter needs 'description'")
        skills[skill_id] = {"description": description}
    return skills


def _cursor_rule(rule_id: str, meta: dict[str, str]) -> str:
    return (
        "---\n"
        f"description: {_yaml_scalar(meta['description'])}\n"
        f"alwaysApply: {'true' if meta['loading'] == 'always' else 'false'}\n"
        "---\n"
        f"<!-- {GENERATED} from agent-env/rules/{rule_id}.md - do not edit. -->\n"
        f"Canonical rule (SSOT): @agent-env/rules/{rule_id}.md\n"
    )


def _skill_adapter(skill_id: str, description: str, *, canonical: str, kind: str, explicit_only: bool) -> str:
    lines = ["---", f"name: {skill_id}", f"description: {_yaml_scalar(description)}"]
    if explicit_only:
        lines.append("disable-model-invocation: true")
    lines += [
        "---",
        f"<!-- {GENERATED} from {canonical} - do not edit. -->",
        f"Read and follow the canonical {kind} (SSOT): `{canonical}`",
        "",
    ]
    return "\n".join(lines)


def _claude_md_block(rules: dict[str, dict[str, str]]) -> str:
    always = [rid for rid, meta in rules.items() if meta["loading"] == "always"]
    on_demand = [(rid, meta) for rid, meta in rules.items() if meta["loading"] != "always"]
    lines = [
        f"{BLOCK_BEGIN} (scripts/governance/sync_agent_env.py) - do not edit; edit agent-env/rules/ and re-run -->",
        "",
        "### Always-on rules (imported from `agent-env/rules/`)",
        "",
    ]
    lines += [f"@agent-env/rules/{rid}.md" for rid in always]
    lines += [
        "",
        "### On-demand rules (invoke as a skill: `/<name>`; canonical text in `agent-env/rules/`)",
        "",
        "| Skill | Invocation | Purpose |",
        "|-------|------------|---------|",
    ]
    for rid, meta in on_demand:
        invocation = "operator only" if meta["loading"] == "explicit" else "operator or model"
        lines.append(f"| `/{rid}` | {invocation} | {meta['description']} |")
    lines += ["", BLOCK_END]
    return "\n".join(lines)


def expected_files() -> dict[Path, str]:
    rules = load_rules()
    skills = load_skills()
    out: dict[Path, str] = {}
    for rid, meta in rules.items():
        out[_CURSOR / "rules" / f"{rid}.mdc"] = _cursor_rule(rid, meta)
        if meta["loading"] != "always":
            out[_CLAUDE / "skills" / rid / "SKILL.md"] = _skill_adapter(
                rid,
                meta["description"],
                canonical=f"agent-env/rules/{rid}.md",
                kind="rule",
                explicit_only=meta["loading"] == "explicit",
            )
    for sid, meta in skills.items():
        canonical = f"agent-env/skills/{sid}/SKILL.md"
        for tool_dir in (_CURSOR, _CLAUDE):
            out[tool_dir / "skills" / sid / "SKILL.md"] = _skill_adapter(
                sid, meta["description"], canonical=canonical, kind="skill", explicit_only=False
            )
    return out


def _generated_on_disk() -> set[Path]:
    """Existing adapter files that carry the GENERATED marker (hand-written files are never touched)."""
    found: set[Path] = set()
    candidates = [
        *(_CURSOR / "rules").glob("*.mdc"),
        *_CURSOR.glob("skills/*/SKILL.md"),
        *_CLAUDE.glob("skills/*/SKILL.md"),
    ]
    for path in candidates:
        if GENERATED in _read(path):
            found.add(path)
    return found


def _rel(path: Path) -> str:
    return path.relative_to(_REPO).as_posix()


def _splice_claude_md(current: str, block: str) -> str | None:
    start = current.find(BLOCK_BEGIN)
    end = current.find(BLOCK_END)
    if start == -1 or end == -1 or end < start:
        return None
    return current[:start] + block + current[end + len(BLOCK_END) :]


def run(*, check: bool) -> int:
    try:
        expected = expected_files()
        block = _claude_md_block(load_rules())
    except ValueError as exc:
        print(f"[ERROR] sync_agent_env: {exc}", file=sys.stderr)
        return 1

    problems: list[str] = []
    writes: dict[Path, str] = {}

    for path, content in expected.items():
        if path.is_file():
            current = _read(path)
            if current == content:
                continue
            if GENERATED not in current:
                problems.append(f"{_rel(path)}: hand-written, not generated; move it into agent-env/ first")
                continue
            problems.append(f"{_rel(path)}: out of date")
        else:
            problems.append(f"{_rel(path)}: missing")
        writes[path] = content

    stale = sorted(_generated_on_disk() - set(expected))
    problems += [f"{_rel(path)}: stale adapter (no canonical source in agent-env/)" for path in stale]

    if not _CLAUDE_MD.is_file():
        problems.append("CLAUDE.md: missing")
    else:
        spliced = _splice_claude_md(_read(_CLAUDE_MD), block)
        if spliced is None:
            problems.append(f"CLAUDE.md: missing '{BLOCK_BEGIN}' ... '{BLOCK_END}' markers")
        elif spliced != _read(_CLAUDE_MD):
            problems.append("CLAUDE.md: generated block out of date")
            writes[_CLAUDE_MD] = spliced

    if check:
        if problems:
            print("[ERROR] sync_agent_env --check: adapters drifted from agent-env/ SSOT:", file=sys.stderr)
            for item in problems:
                print(f"  - {item}", file=sys.stderr)
            print("  fix: uv run python scripts/governance/sync_agent_env.py", file=sys.stderr)
            return 1
        print(f"[INFO] sync_agent_env --check: OK ({len(expected)} adapters + CLAUDE.md block)")
        return 0

    handwritten = [p for p in problems if "hand-written" in p or "markers" in p or p == "CLAUDE.md: missing"]
    if handwritten:
        for item in handwritten:
            print(f"[ERROR] sync_agent_env: {item}", file=sys.stderr)
        return 1
    for path, content in writes.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
    for path in stale:
        path.unlink()
        if path.parent != _CURSOR / "rules" and not any(path.parent.iterdir()):
            path.parent.rmdir()
    print(f"[INFO] sync_agent_env: wrote {len(writes)}, removed {len(stale)} stale ({len(expected)} adapters)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify adapters match agent-env/ without writing")
    return run(check=parser.parse_args(argv).check)


if __name__ == "__main__":
    raise SystemExit(main())
