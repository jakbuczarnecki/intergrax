"""Generate advisory adapter fragments for non-Cursor harnesses (Claude / Codex stubs)."""

from __future__ import annotations

from pathlib import Path

import yaml

_REPO = Path(__file__).resolve().parents[2]
_ACP = _REPO / "governance" / "agent-control-plane"
_ADAPTERS = _ACP / "adapters"


def _role_summary() -> str:
    doc = yaml.safe_load((_ACP / "role_registry.yaml").read_text(encoding="utf-8"))
    roles = doc.get("roles", {})
    lines = ["# Delivery DevOS roles (generated fragment — ADVISORY)", ""]
    for name in sorted(roles):
        desc = roles[name].get("description", "")
        lines.append(f"- **{name}**: {desc}")
    lines.append("")
    lines.append("SSOT: `governance/agent-control-plane/role_registry.yaml`")
    lines.append("")
    return "\n".join(lines)


def _subagent_summary() -> str:
    doc = yaml.safe_load((_ACP / "role_registry.yaml").read_text(encoding="utf-8"))
    sub = doc.get("subagent_role_map", {})
    lines = [
        "# Subagent role map (generated — ADVISORY)",
        "",
        "| Subagent | maps_to | max_parallel |",
        "|----------|---------|--------------|",
    ]
    for name, meta in sorted(sub.items()):
        lines.append(f"| {name} | {meta.get('maps_to')} | {meta.get('max_parallel')} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    _ADAPTERS.mkdir(parents=True, exist_ok=True)
    claude_dir = _ADAPTERS / "claude"
    codex_dir = _ADAPTERS / "codex"
    claude_dir.mkdir(exist_ok=True)
    codex_dir.mkdir(exist_ok=True)

    fragment = _role_summary() + "\n" + _subagent_summary()
    banner = "<!-- GENERATED by sync_adapter_fragments.py — ADVISORY; merge manually into harness docs -->\n\n"

    (claude_dir / "DELIVERY_DEVOS.fragment.md").write_text(banner + fragment, encoding="utf-8")
    (codex_dir / "AGENTS.fragment.md").write_text(banner + fragment, encoding="utf-8")
    print(f"[INFO] wrote {_ADAPTERS.relative_to(_REPO)}/claude/DELIVERY_DEVOS.fragment.md")
    print(f"[INFO] wrote {_ADAPTERS.relative_to(_REPO)}/codex/AGENTS.fragment.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
