def qualification_status_from_disposition(scenario_id: str) -> CertificationStatus:
    d = disposition_for(scenario_id)
    if d is None or d.semantic_match is not ProofBindingResult.EXACT_PROOF:
        return CertificationStatus.QUALIFICATION_PENDING
    return CertificationStatus.QUALIFIED


