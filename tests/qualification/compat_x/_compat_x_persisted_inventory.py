def _family(
    family_id: str,
    payload: str,
    owner: str,
    writers: tuple[str, ...],
    readers: tuple[str, ...],
    storage: PersistedStorageKind,
    version_disp: PersistedVersionDisposition,
    current_version: str | None,
    version_owner: str | None,
    migration_disp: MigrationDisposition,
    migration_owner: str | None,
    evidence: tuple[str, ...],
    frz: tuple[str, ...] = ("FRZ-CMP-03",),
    notes: str = "",
) -> PersistedSchemaFamily:
    return PersistedSchemaFamily(
        family_id=family_id,
        canonical_payload_type=payload,
        owner_module_path=owner,
        writer_paths=writers,
        reader_paths=readers,
        storage_kind=storage,
        version_disposition=version_disp,
        current_version=current_version,
        version_owner_path=version_owner,
        migration_disposition=migration_disp,
        migration_owner_path=migration_owner,
        evidence_paths=evidence,
        frz_cmp_tags=frz,
        notes=notes,
    )


