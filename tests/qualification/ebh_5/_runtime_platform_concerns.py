def roadmap_domain_for_integration_category(category: IntegrationCategory) -> RoadmapVendorDomain:
    return _INTEGRATION_CATEGORY_DOMAIN.get(
        category,
        RoadmapVendorDomain.DISCOVERED,
    )


def _fixed_sqlite_row(
    concern_id: str,
    domain: RoadmapVendorDomain,
    *,
    semantic_owner: str,
    contract: str,
    composition_owner: str,
    impl: str,
    vendor_path: str,
    consumers: tuple[str, ...],
    frz: tuple[str, ...],
    debt: str = "",
) -> VendorBackendConcernRecord:
    return VendorBackendConcernRecord(
        concern_id=concern_id,
        domain=domain,
        semantic_owner=semantic_owner,
        canonical_contract_or_port=contract,
        composition_selection_owner=composition_owner,
        concrete_implementation=impl,
        extensibility_promised=ExtensibilityPromised.NO,
        configuration_profile_source="FIXED — Tier-3 composition path / DATA_DIR",
        lifecycle_activation_authority=composition_owner,
        vendor_code_location=vendor_path,
        core_consumers=consumers,
        core_change_required_to_switch=CoreChangeToSwitch.ADAPTER_ONLY,
        fallback_behavior="fail-closed — no silent alternate backend",
        structural_replaceability_evidence_id="EBH_5_ALLOWED_FIXED_SUBSTRATE_DECISIONS",
        behavioral_qualification_evidence_id="N/A",
        frz_criteria=frz,
        extensibility_classification=ExtensibilityClassification.FIXED_SUBSTRATE,
        conclusion=ConcernConclusion.ACCEPTED,
        outstanding_debt=debt,
        config_x_concern_id=None,
        production_effective=True,
    )


