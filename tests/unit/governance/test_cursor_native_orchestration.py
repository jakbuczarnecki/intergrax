"""Cursor direct execution contracts; factory is optional; Claude Stop behavior is untouched."""

from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
CURSOR = ROOT / ".cursor"
CLAUDE = ROOT / ".claude"


def test_cursor_has_no_mandatory_factory_stop_hook() -> None:
    hooks = json.loads((CURSOR / "hooks.json").read_text(encoding="utf-8"))["hooks"]
    assert "stop" not in hooks
    assert "subagentStart" in hooks
    assert "beforeShellExecution" in hooks
    assert hooks["beforeShellExecution"][0]["failClosed"] is True


def test_claude_keeps_its_independent_stop_hook_and_skill() -> None:
    settings = json.loads((CLAUDE / "settings.json").read_text(encoding="utf-8"))
    assert any("igx_stop_guard.py" in hook["command"] for group in settings["hooks"]["Stop"] for hook in group["hooks"])
    skill = (CLAUDE / "skills/igx-run-plan/SKILL.md").read_text(encoding="utf-8")
    assert "agent-env/skills/igx-run-plan/SKILL.md" in skill
    assert "Stop hook" in skill


def test_cursor_legacy_command_is_a_native_alias() -> None:
    text = (CURSOR / "skills/igx-run-plan/SKILL.md").read_text(encoding="utf-8")
    assert "GENERATED by scripts/governance/sync_agent_env.py" in text
    assert "igx-native-run-plan/SKILL.md" in text
    assert "Do not invoke `igx_stop_guard.py start|stop`" in text
    assert "Read and follow the canonical skill (SSOT)" not in text


def test_cursor_direct_execution_rule_replaces_factory() -> None:
    assert not (CURSOR / "rules/igx-factory.mdc").exists()
    rule = (CURSOR / "rules/igx-cursor-direct-execution.mdc").read_text(encoding="utf-8")
    assert "alwaysApply: true" in rule
    assert "GENERATED by scripts/governance/sync_agent_env.py" in rule
    assert "voluntary" in rule.lower()
    skill = (CURSOR / "skills/igx-native-run-plan/SKILL.md").read_text(encoding="utf-8")
    assert "Not the default" in skill or "voluntary" in skill.lower()
    assert "igx-cursor-direct-execution" in skill
    metadata = yaml.safe_load(skill.split("---", 2)[1])
    assert metadata["name"] == "igx-native-run-plan"


def test_integration_role_is_still_cursor_only() -> None:
    policy = yaml.safe_load((ROOT / "governance/agent-control-plane/role_registry.yaml").read_text(encoding="utf-8"))
    assert policy["roles"]["integrator"]["runtime"] == "cursor"
    assert policy["subagent_role_map"]["igx-integrator"]["runtime"] == "cursor"
    assert policy["roles"]["orchestrator"]["may_commit"] is False
    assert not (CLAUDE / "agents/igx-integrator.md").exists()


def test_cursor_core_allows_direct_commits_on_checkout() -> None:
    core = (CURSOR / "rules/intergrax-core.mdc").read_text(encoding="utf-8")
    assert "igx-cursor-direct-execution.mdc" in core
    assert "current checkout" in core
    assert "push origin development" in core
    assert "factory/<plan-id>/int" not in core
    assert "igx_factory.py park" not in core
