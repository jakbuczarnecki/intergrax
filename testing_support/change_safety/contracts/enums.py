from __future__ import annotations

from enum import StrEnum


class ImpactStatus(StrEnum):
    COMPLETE = "COMPLETE"
    PARTIAL = "PARTIAL"
    INTEGRITY_FAILURE = "INTEGRITY_FAILURE"
    REFUSED = "REFUSED"


class SelectionStatus(StrEnum):
    SELECTED = "SELECTED"
    CONSERVATIVE_FULL = "CONSERVATIVE_FULL"
    REFUSED_INTEGRITY = "REFUSED_INTEGRITY"


class CompatibilityAtChangeResult(StrEnum):
    COMPATIBLE = "COMPATIBLE"
    INCOMPATIBLE = "INCOMPATIBLE"
    MIGRATION_REQUIRED = "MIGRATION_REQUIRED"
    UNKNOWN = "UNKNOWN"


class WorkflowEvolutionDecision(StrEnum):
    SAFE_IN_PLACE = "SAFE_IN_PLACE"
    VERSIONED_DEPLOY = "VERSIONED_DEPLOY"
    MIGRATE = "MIGRATE"
    REJECT = "REJECT"
    EXPLICITLY_UNSUPPORTED = "EXPLICITLY_UNSUPPORTED"


class DeploySafetyVerdict(StrEnum):
    ELIGIBLE = "ELIGIBLE"
    ELIGIBLE_WITH_DRAIN = "ELIGIBLE_WITH_DRAIN"
    REFUSE = "REFUSE"


class DeployRefusalReason(StrEnum):
    PERSISTED_STATE_INCOMPATIBLE = "PERSISTED_STATE_INCOMPATIBLE"
    DURABLE_STATE_FORWARD_ONLY = "DURABLE_STATE_FORWARD_ONLY"
    INFLIGHT_PINS = "INFLIGHT_PINS"
    CONTRACT_INCOMPATIBLE = "CONTRACT_INCOMPATIBLE"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
